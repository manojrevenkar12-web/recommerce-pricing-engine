"""reports/EVALUATION.md from reports/evaluation.json."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from rpe.config import REPORTS
from rpe.evaluation.gate import decide, format_lines

LABELS = {
    "engine_sell_only": "Buy offers and buy/no-buy",
    "engine_buy_only": "Dynamic sell prices and liquidation",
    "engine_no_market_model": "Market price model",
    "engine_no_capacity": "Warehouse shelf price",
    "engine_no_long_term": "Long-term seller value in offers",
}


def _e(x: float) -> str:
    return f"{x:,.0f}"


def write(path: Path = REPORTS / "evaluation.json", out: Path = REPORTS / "EVALUATION.md") -> str:
    r: dict[str, Any] = json.loads(path.read_text())
    ok, lines = decide(r)
    bt, m, ex = r["backtest"], r["models"], r["experiments"]
    h, up = bt["headline"], bt["uplift"]
    L = [
        "# Evaluation",
        "",
        f"Generated by `rpe eval` at {r['generated_at']} on models trained at {r['model_card']['trained_at']} "
        f"(history {r['model_card']['history'][0]} to {r['model_card']['history'][1]}, data {r['model_card']['data_fingerprint']}). "
        f"Release gate: **{'passed' if ok else 'FAILED'}**.",
        "",
        "Everything below is measured on a simulated market whose truth the models never see: the engine learns from the exported "
        "history only, and the evaluator scores decisions against the simulator's hidden demand, prices and sellers.",
        "",
        "## Engine against today's rules",
        "",
        f"Six months forward from the end of 2025, {h['seeds']} market replays, the same sellers and market for both policies. "
        "**Value** is the cash contribution of the period plus the value of the stock and parcels held at the end, valued the same "
        "way for both (true demand at the true market price).",
        "",
        "| | rules (mean) | engine - rules | 95% interval | |",
        "|---|---|---|---|---|",
    ]
    for k, label in [
        ("value", "Value, EUR"),
        ("cash", "Cash contribution in the period, EUR"),
        ("value_incl_sellers", "Value incl. returning sellers, EUR"),
        ("revenue", "Revenue, EUR"),
        ("revenue_minus_purchases", "Revenue minus purchase spend, EUR"),
        ("pending_returns", "Sellers who will come back"),
        ("units_sold", "Units sold"),
        ("units_bought", "Units bought"),
    ]:
        u = up[k]
        L.append(f"| {label} | {_e(u['control'])} | {u['diff']:+,.0f} ({u['pct']:+.1f}%) | {u['lo']:+,.0f} to {u['hi']:+,.0f} | |")
    runs = [x for x in bt["runs"]]
    L += [
        "",
        "| policy | seed | value | cash | end stock value | units sold | bought | liquidated | avg sale price | avg paid | baskets sent | max fill |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for x in sorted(runs, key=lambda x: (x["seed"], x["policy"])):
        L.append(
            f"| {x['policy']} | {x['seed']} | {_e(x['value'])} | {_e(x['cash'])} | {_e(x['end_stock_value'])} | {_e(x['units_sold'])} | {_e(x['units_bought'])} | "
            f"{_e(x['units_liquidated'])} | {x['avg_sale_price']:.2f} | {x['avg_paid']:.2f} | {x['basket_sent_rate']:.1%} | {x['max_fill']:.1%} |"
        )
    lr = bt.get("long_run", {})
    if "engine" in lr:
        L += [
            "",
            "**Two years, one replay.** Cash contribution per half-year (EUR), rules vs engine: "
            + ", ".join(
                f"{_e(b)} vs {_e(e)}" for b, e in zip(lr["baseline"]["cash_by_half_year"], lr["engine"]["cash_by_half_year"], strict=False)
            )
            + f". In the second year the engine earns {lr['second_year_cash_uplift_pct']:+.1f}% more cash: the first months are an investment in better stock.",
        ]
    g = bt["guardrails"]
    L += [
        "",
        f"Guardrails: {g.get('prices_checked', 0):,} engine prices re-checked independently; violations: "
        + ", ".join(f"{k} {v}" for k, v in g.items() if k != "prices_checked")
        + ".",
    ]
    L += [
        "",
        "## What each part is worth",
        "",
        "Engine with vs without the part, same replays (seeds " + ", ".join(str(s) for s in bt.get("ablation_seeds", [])) + "):",
        "",
        "| part | value over six months, EUR | 95% interval | incl. returning sellers |",
        "|---|---|---|---|",
    ]
    for k, v in sorted(bt["ablations"].items(), key=lambda kv: -kv[1]["value_of_part"]):
        L.append(
            f"| {LABELS.get(k, k)} | {v['value_of_part']:+,.0f} | {v['lo']:+,.0f} to {v['hi']:+,.0f} | {v['value_of_part_incl_sellers']:+,.0f} |"
        )
    L += ["", "## Stress scenarios", ""]
    for kind, title in (
        ("dev", "Development scenarios (used while building)"),
        ("heldout", "Held-out scenarios (written without seeing the engine; current run)"),
    ):
        sc = bt["scenarios"][kind]
        if not sc:
            continue
        L += [
            f"**{title}**",
            "",
            "| scenario | rules: value | engine: value | engine vs rules | sellers coming back (engine / rules) | engine max fill | overflow unit-days (engine / rules) | bought while full (engine / rules) | violations |",
            "|---|---|---|---|---|---|---|---|---|",
        ]
        for x in sc:
            L.append(
                f"| {x['scenario']} | {_e(x['baseline_value'])} | {_e(x['engine_value'])} | {x['uplift_pct']:+.1f}% | {x['engine_returns_vs_baseline']:.2f} | "
                f"{x['engine_max_fill']:.1%} | {x['engine_overflow_unit_days']:,} / {x['baseline_overflow_unit_days']:,} | "
                f"{x.get('engine_items_bought_while_full', 0):,} / {x.get('baseline_items_bought_while_full', 0):,} | {x['engine_guardrail_violations']} |"
            )
        L.append("")
    fr = bt["scenarios"].get("heldout_first_run")
    if fr:
        L += [
            f"First run of the held-out scenarios ({fr['recorded_at']}): see [scenarios/heldout/FIRST_RUN.md](../scenarios/heldout/FIRST_RUN.md).",
            "",
        ]
    mp = m["market_price"]
    L += [
        "## Models against the truth",
        "",
        "**Market price** (end of 2025, mean absolute log error; median absolute % error):",
        "",
        "| titles | engine | today's rule |",
        "|---|---|---|",
        f"| with competitor offers ({mp['feed_titles']['engine']['titles']:,}) | {mp['feed_titles']['engine']['mean_abs_log_error']:.3f}; {mp['feed_titles']['engine']['median_abs_pct_error']:.1f}% | last competitor price: {mp['feed_titles']['rule_last_price']['mean_abs_log_error']:.3f}; {mp['feed_titles']['rule_last_price']['median_abs_pct_error']:.1f}% |",
        f"| without (cold start, {mp['cold_start_titles']['engine']['titles']:,}) | {mp['cold_start_titles']['engine']['mean_abs_log_error']:.3f}; {mp['cold_start_titles']['engine']['median_abs_pct_error']:.1f}% | 40% of list price: {mp['cold_start_titles']['rule_share_of_list_price']['mean_abs_log_error']:.3f}; {mp['cold_start_titles']['rule_share_of_list_price']['median_abs_pct_error']:.1f}% |",
        "",
        f"Cold-start P10-P90 range contains the true price for {mp['cold_start_titles']['p10_p90_coverage']:.0%} of titles (80% intended).",
        "",
    ]
    pr = m["price_response"]
    L += [
        "**Price response** recovered from the randomised price tests (beta: how fast demand falls with price):",
        "",
        "| category | estimated | true |",
        "|---|---|---|",
    ]
    L += [f"| {c} | {v['estimated']:.2f} | {v['true']:.2f} |" for c, v in pr["beta"].items()]
    cf = pr["condition_factors"]
    L += [
        "",
        f"Mean absolute error {pr['beta_mean_abs_rel_error']:.0%}, largest {pr['beta_max_abs_rel_error']:.0%}. Copies sharing a title's buyers: power {pr['depth_power']['estimated']:.2f} (true 1.00). "
        "Condition price factors: " + ", ".join(f"{g} {v['estimated']:.3f} (true {v['true']:.2f})" for g, v in cf.items()) + ".",
        "",
    ]
    dc, sb = m["demand_calibration"], m["sellability_90d"]
    L += [
        f"**Demand**: predicted / true sales intensity of the {dc['units']:,} units in stock: {dc['overall_ratio']:.3f} overall; by days listed "
        + ", ".join(f"{k} {v:.2f}" for k, v in dc["by_age_days"].items())
        + "; by category "
        + ", ".join(f"{k} {v:.2f}" for k, v in dc["by_category"].items())
        + ".",
        "",
        f"**Sellability** (P(sold within 90 days) at the market price, checked against 90 days of simulated sales): predicted {sb['predicted_mean']:.1%}, realised {sb['realised_mean']:.1%}, "
        f"calibration error {sb['expected_calibration_error']:.3f}, AUC {sb['auc']:.3f} (sales rank alone, as the rules use it: {sb['auc_sales_rank_rule']:.3f}).",
        "",
        f"**Seller acceptance**: mean absolute error against the true keep probability {m['acceptance']['mean_abs_error']:.3f} on {m['acceptance']['offers']:,} offers "
        f"(predicted {m['acceptance']['predicted_mean']:.1%}, true {m['acceptance']['true_mean']:.1%}).",
        "",
        f"**Grading**: log loss {m['grading']['log_loss_model']:.3f} vs {m['grading']['log_loss_overall_rates']:.3f} for overall grade rates.",
        "",
    ]
    ss, aa, bs = ex["sell_side_price_test"], ex["sell_side_price_test"]["a_a"], ex["buy_side_offer_test"]
    L += [
        "## Does the experiment framework tell the truth?",
        "",
        f"- **A/A tests**: {aa['splits']} random splits of a run with no difference. Analysed by title (the unit of randomisation) {aa['false_positive_rate_by_title']:.1%} "
        f"claim a difference at 5%; analysed copy by copy, as if copies were independent, {aa['false_positive_rate_by_copy']:.1%}.",
        f"- **Peeking**: checked every day for 28 days, a fixed-horizon test stopped at the first p < 0.05 rejects in {ex['peeking_null']['naive_reject_any_look']:.1%} of A/A tests; "
        f"the always-valid p-value (mSPRT) in {ex['peeking_null']['always_valid_reject']:.1%}. With a real effect of 0.1 sd it detects {ex['peeking_with_effect']['always_valid_reject']:.0%} and stops after {ex['peeking_with_effect']['mean_looks_to_stop']:.1f} looks on average.",
        f"- **Sell-side price test** (engine vs rule prices, randomised by title, 91 days, outcome per title: sales net of fees and handling, holding cost, liquidation, book value of what is left): "
        f"the 95% interval contained the true effect in {ss['coverage']:.0%} of {len(ss['per_seed'])} replays ({ss['cuped_coverage']:.0%} with CUPED, which removed "
        + ", ".join(f"{x['cuped_variance_removed']:.0%}" for x in ss["per_seed"])
        + " of the variance).",
        "",
        "| replay | titles | true effect per title, EUR | estimate | 95% interval | with CUPED | sample ratio p |",
        "|---|---|---|---|---|---|---|",
    ]
    for x in ss["per_seed"]:
        L.append(
            f"| {x['seed']} | {x['titles']:,} | {x['true_effect_per_title']:+.3f} | {x['estimate']:+.3f} | {x['ci'][0]:+.3f} to {x['ci'][1]:+.3f} | {x['cuped_ci'][0]:+.3f} to {x['cuped_ci'][1]:+.3f} | {x['srm_p']:.2f} |"
        )
    L += [
        "",
        f"- **Buy-side offer test** (engine vs rule offers, randomised by seller, {bs['sellers']:,} sellers): the surrogate index predicted a change in the 120-day return rate of "
        f"{bs['surrogate_effect_on_return_rate']['diff']:+.3f} ({bs['surrogate_effect_on_return_rate']['ci'][0]:+.3f} to {bs['surrogate_effect_on_return_rate']['ci'][1]:+.3f}) after 30 days; "
        f"the realised change four months later was {bs['realised_effect_on_return_rate']['diff']:+.3f} ({bs['realised_effect_on_return_rate']['ci'][0]:+.3f} to {bs['realised_effect_on_return_rate']['ci'][1]:+.3f}). "
        f"Baskets sent: {bs['basket_sent_rate']['treatment']:.1%} with engine offers, {bs['basket_sent_rate']['control']:.1%} with rule offers.",
        "",
    ]
    c = r["contracts"]
    L += [
        "## Data contracts",
        "",
        f"Injected bad rows: {c['injected']}. Quarantined: {c['quarantined']}. Every injected row caught: {c['bad_rows_caught'] == 1.0}; valid rows quarantined: {c['good_rows_quarantined']}.",
        "",
    ]
    if r.get("api"):
        a = r["api"]
        L += [
            "## API",
            "",
            f"Buy quote for {a['items']} items: p50 {a['p50_ms']:.1f} ms, p95 {a['p95_ms']:.1f} ms over {a['requests']} requests (in-process client)."
            "",
        ]
    L += ["## Release gate", "", "```", *format_lines(lines), "```", "", f"Runtime: {r['seconds']}.", ""]
    text = "\n".join(L)
    out.write_text(text)
    return text
